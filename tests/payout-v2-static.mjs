import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const server=await readFile(new URL('../server-payout-preload-v2.mjs',import.meta.url),'utf8');
const client=await readFile(new URL('../assets/server-payout-control-v2.js',import.meta.url),'utf8');
const monitor=await readFile(new URL('../assets/server-monitor-payout-v2.js',import.meta.url),'utf8');
const wrapper=await readFile(new URL('../assets/shared-machine-v176.js',import.meta.url),'utf8');
assert.ok(server.includes("source:'per-player-game'"),'control must identify per-player x game source');
assert.ok(!server.includes('globalWeight'),'global payout must not affect control');
assert.ok(server.includes('actualWithPrior(gameState)'),'each game must use its own prior-stabilized history');
assert.ok(server.includes('rollingHorizonBet'),'old results must decay in the control window');
assert.ok(server.includes("lastAdjustedKey===key"),'same ball must not adjust twice');
assert.ok(client.includes('await waitForBall(ball)'),'checkpoint must wait for game-side ball processing');
assert.ok(client.includes('roundWin+=win'),'nWIN must be reported at each completed ball');
assert.ok(client.includes('debugPayoutTarget=weighted'),'server must directly overwrite the lexical debug target');
assert.ok(!client.includes("button.click()"),'server payout must not depend on integer-only debug button');
assert.ok(client.includes("for(const method of ['reset','freshBoard'])"),'each game generation must use its own rate');
assert.ok(client.includes('appliedRate:appliedRates.get(id)'), 'actual generation rate must be sent back to server');
assert.ok(monitor.includes('PLAYER × GAME 独立PO制御'),'monitor must explain independent control');
assert.ok(monitor.includes('TOTAL ${fmt(item.roundWin)} WIN'),'monitor must show nWIN for every processed ball');
assert.ok(monitor.includes('実適用'),'monitor must compare instructed and applied rates');
assert.ok(wrapper.includes('server-payout-control-v2.js?v=209'),'v209 client control must load in private game scope');
console.log('per-player x game payout and live nWIN static guards passed');
