import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';

const source=await fs.readFile(new URL('../assets/choco-dig.js',import.meta.url),'utf8');
const beforeClass=source.slice(0,source.indexOf('class ChocoDigEngine extends Engine'));
assert.ok(beforeClass.length>10000,'production Canyon core loaded');
const ctx=vm.createContext({console});
vm.runInContext(beforeClass,ctx,{timeout:10000});
const run=(code)=>JSON.parse(JSON.stringify(vm.runInContext(code,ctx,{timeout:10000})));
const fresh=(entries)=>{const grid=Array.from({length:12},()=>Array(7).fill(null));for(const [r,c,t]of entries)grid[r][c]=t;return grid;};
ctx.makeGrid=fresh;
const single=fresh([[3,3,{id:1,color:0,sectionId:'a',number:null}]]);
ctx.trial=single;
const next=run("chocoExcavate(trial,[],{trace:true,uid:1,refill:false,rulesRevision:8})");
assert.equal(next.removed.length,1,'single fallen cake must melt on landing');
assert.equal(next.removed[0].tile.id,1);
assert.equal(next.grid.flat().filter(Boolean).length,0);
assert.ok(next.fallSteps>=1);
assert.ok(next.timeline.some(e=>e.phase==='canyonFall'));
assert.ok(next.timeline.some(e=>e.phase==='canyonMelt'));
const old=run("chocoExcavate(trial,[],{trace:false,uid:1,refill:false,rulesRevision:7})");
assert.equal(old.removed.length,0,'historical small groups do not auto-melt');
assert.equal(old.grid[11][3].id,1);
const cluster=fresh([[3,2,{id:1,color:0,sectionId:'a'}],[3,3,{id:2,color:0,sectionId:'a'}],[4,3,{id:3,color:0,sectionId:'a'}]]);
ctx.trial=cluster;
const triple=run("chocoExcavate(trial,[],{trace:false,uid:3,refill:false,rulesRevision:8})");
assert.equal(triple.removed.length,3,'all three cake tiles must melt at ground');
assert.ok(triple.fallSteps>0);
const disjoint=fresh([[11,1,{id:1,color:0,sectionId:'a'}],[11,2,{id:2,color:0,sectionId:'b'}]]);
ctx.trial=disjoint;
assert.deepEqual(run("chocoGroups(trial).groups.map(x=>x.map(v=>v.tile.id))"),[[1],[2]],'gravity cannot join unlike original sections');
ctx.trial=fresh([[11,1,{id:1,color:0,sectionId:'a'}],[11,2,{id:2,color:0,sectionId:'a'}]]);
assert.deepEqual(run("chocoGroups(trial).groups.map(x=>x.map(v=>v.tile.id))"),[[1,2]],'original section remains connected');
ctx.world={strata:[],depth:0,startDepth:0,uid:0,seed:902,fruitCount:0,fruitState:0,bonusResolvedDepth:0,nextSugar:18,rulesRevision:8};
const world=run("chocoFillRows(world);world");
assert.equal(world.strata.length,12);
assert.ok(world.strata.flat().filter(t=>t?.color>=0).every(t=>typeof t.sectionId==='string'));
assert.equal(world.strata.flat().filter(t=>t?.item==='ore').length,0,'new underground prizes must be fruit, not ores');
assert.ok(world.strata.flat().some(t=>t?.item==='fruit-prize'));
assert.match(source,/function chocoClassicCakeSprite/);
assert.equal(run('CHOCO_FRUIT_REVISION'),8,'legacy fruit presentation threshold remains v8 when new worlds advance');
assert.match(source,/const chainSections=e.rulesRevision>=CHOCO_FRUIT_REVISION\?new Set\(\):chocoChainSections/);
assert.match(source,/const chocoFruitArtCache=new Map\(\)/);
console.log('CHOCO_V288_GRAVITY_FRUIT_PASS',JSON.stringify({worldRows:world.strata.length,fruitPrizes:world.strata.flat().filter(t=>t?.item==='fruit-prize').length,fallenSingle:true,fallenTriple:true,separateRegions:true,classicCakes:true}));
